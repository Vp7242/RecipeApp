    /** Scores every recipe against ML Kit labels; returns best matches first. */
    fun match(labels: List<Pair<String, Float>>, max: Int = 3): List<Recipe> =
        all.map { r ->
            val score = labels.sumOf { (text, conf) ->
                val t = text.lowercase()
                r.keywords.maxOfOrNull { k ->
                    when {
                        t == k -> 1.0
                        t.contains(k) || k.contains(t) -> 0.5
                        else -> 0.0
                    }
                }?.times(conf.toDouble()) ?: 0.0
            }
            r to score
        }.filter { it.second > 0 }.sortedByDescending { it.second }.take(max).map { it.first }
